// Claude Code sessions stored on this computer, for bridge_read_chat: found by
// title, folder or text, and read as units (see src/readchat.mjs).
//
// <claude config dir>/projects/<folder key>/<session id>.jsonl, one record
// per line, append-only. The sidebar title is in <folder key>/<session
// id>/custom-title.json and in "custom-title" records (the last one wins). A
// session moved to another folder (a worktree) can sit under several folder
// keys; the newest file is the session. The format is Claude Code's own and
// undocumented: only known shapes are read, the rest is left out and counted.

import fs from "node:fs";
import path from "node:path";
import { claudeConfigDir } from "./platform.mjs";
import { normalizeName, inFolder, MAX_COMMAND, assemble, visible } from "./readchat.mjs";

export const MAX_FILES = 2_000;
const MAX_SEARCH_BYTES = 400 * 1024 * 1024;
const TAIL = 512 * 1024;
const SNIPPET = 160;

// Claude Code's own blocks in user turns: reminders and notices it adds,
// sometimes before the user's own words in the same message. They are taken
// out and the rest kept; a message with nothing else is the app's own.
const INJECTED = /<(task-notification|local-command-[a-z]+|command-(?:name|message|args)|system-reminder)\b[^>]*>[\s\S]*?<\/\1>/g;
const CAVEAT = /^\s*Caveat: The messages below were generated by the user while running local commands[^\n]*\n?/;
export const humanText = (t) => String(t ?? "").replace(INJECTED, "").replace(CAVEAT, "").trim();

const projectsDir = () => path.join(claudeConfigDir(), "projects");

const gone = (e) => e.code === "ENOENT" || e.code === "ENOTDIR";
const problem = (p, e) => `${p} (${e.code ?? e.message})`;

// Every session, newest first, one file per session id, and what couldn't
// be read. No projects folder at all is no sessions; a folder that can't be
// read is a problem, never taken for an empty one.
export function scanSessions() {
  const byId = new Map();
  const problems = [];
  let dirs = [];
  try {
    dirs = fs.readdirSync(projectsDir(), { withFileTypes: true }).filter((d) => d.isDirectory());
  } catch (e) {
    if (e.code === "ENOENT") return { sessions: [], problems };
    throw new Error(`can't read ${problem(projectsDir(), e)}`);
  }
  for (const d of dirs) {
    const dir = path.join(projectsDir(), d.name);
    let names = [];
    try {
      names = fs.readdirSync(dir).filter((f) => f.endsWith(".jsonl"));
    } catch (e) {
      if (!gone(e)) problems.push(problem(dir, e));
      continue;
    }
    for (const f of names) {
      const file = path.join(dir, f);
      let st;
      try {
        st = fs.statSync(file);
      } catch (e) {
        if (!gone(e)) problems.push(problem(file, e));
        continue;
      }
      if (!st.isFile()) {
        problems.push(`${file} (not a file)`);
        continue;
      }
      const id = f.slice(0, -".jsonl".length);
      const prev = byId.get(id);
      if (!prev || st.mtimeMs > prev.mtime) byId.set(id, { id, file, mtime: st.mtimeMs, size: st.size });
    }
  }
  return { sessions: [...byId.values()].sort((a, b) => b.mtime - a.mtime), problems };
}

export const claudeSessions = () => scanSessions().sessions;

const parse = (line) => {
  try {
    return JSON.parse(line);
  } catch {
    return null;
  }
};

function readTail(file, bytes) {
  const fd = fs.openSync(file, "r");
  try {
    const size = fs.fstatSync(fd).size;
    const start = Math.max(0, size - bytes);
    const buf = Buffer.alloc(size - start);
    fs.readSync(fd, buf, 0, buf.length, start);
    const lines = buf.toString("utf8").split("\n");
    if (start > 0) lines.shift(); // cut mid-line
    return lines;
  } finally {
    fs.closeSync(fd);
  }
}

const textOf = (content) =>
  typeof content === "string"
    ? content
    : (content ?? [])
        .filter((b) => b.type === "text")
        .map((b) => b.text)
        .join("\n");

// Title and folder, from the end of the file (titles are written again and
// again, and every record carries the folder)
export function claudeMeta(s) {
  let name = null;
  const titleFile = path.join(path.dirname(s.file), s.id, "custom-title.json");
  try {
    name = JSON.parse(fs.readFileSync(titleFile, "utf8")).customTitle ?? null;
  } catch (e) {
    // no title file is common; one that can't be read might hold the name asked for
    if (!gone(e)) throw new Error(problem(titleFile, e));
  }
  let folder = null;
  for (const line of readTail(s.file, TAIL).reverse()) {
    if (name && folder) break;
    if (!line.includes('"custom-title"') && !line.includes('"cwd"')) continue;
    const r = parse(line);
    if (!r) continue;
    if (!name && r.type === "custom-title" && r.customTitle) name = r.customTitle;
    if (!folder && typeof r.cwd === "string") folder = r.cwd;
  }
  if (!name && s.size > TAIL) {
    const all = fs.readFileSync(s.file, "utf8");
    const i = all.lastIndexOf('"type":"custom-title"');
    if (i > -1) name = parse(all.slice(all.lastIndexOf("\n", i) + 1, all.indexOf("\n", i) === -1 ? undefined : all.indexOf("\n", i)))?.customTitle ?? null;
  }
  let untitled = false;
  if (!name) {
    untitled = true;
    for (const line of readTail(s.file, Infinity)) {
      const r = parse(line);
      if (r?.type === "user" && !r.isSidechain && !r.isMeta && !r.isCompactSummary) {
        const t = humanText(textOf(r.message?.content));
        if (t) {
          name = `(untitled) ${t.replace(/\s+/g, " ").slice(0, 60)}`;
          break;
        }
      }
    }
    name ??= "(untitled)";
  }
  return { app: "claude", id: s.id, name, folder, updated: s.mtime, untitled };
}

// ------------------------------------------------------------------ finding

// { candidates, complete, scope, next }: by title and/or text, within the
// newest MAX_FILES sessions from `offset` on, and a byte budget for text
export function findClaude({ name, search, folder, self, offset = 0 }) {
  const { sessions: all, problems } = scanSessions();
  const slice = all.slice(offset, offset + MAX_FILES);
  const want = name ? normalizeName(name) : null;
  const term = search ? search.toLowerCase() : null;
  const candidates = [];
  let bytes = 0;
  let looked = 0;
  for (const s of slice) {
    if (term && bytes + s.size > MAX_SEARCH_BYTES && looked) break;
    looked++;
    if (s.id === self) continue;
    try {
      const meta = claudeMeta(s);
      if (folder && !inFolder(meta.folder, folder)) continue;
      if (want && !normalizeName(meta.name).includes(want)) continue;
      if (term) {
        bytes += s.size;
        const snippet = searchFile(s.file, term);
        if (snippet === null) continue;
        meta.snippet = snippet;
      }
      candidates.push(meta);
    } catch (e) {
      // deleted meanwhile is gone; anything else might have been a match
      if (!gone(e)) problems.push(problem(s.file, e));
    }
  }
  const next = offset + looked;
  const scanned = next >= all.length;
  return {
    candidates,
    // a session that couldn't be read might have matched
    complete: scanned && !problems.length,
    problems,
    scope: `${looked} of ${all.length} sessions${scanned ? "" : `, the newest from ${offset + 1}`}`,
    next: scanned ? null : next,
  };
}

// The text around the first match in a user or assistant message, or null
function searchFile(file, term) {
  const raw = fs.readFileSync(file, "utf8");
  if (!raw.toLowerCase().includes(term)) return null;
  for (const line of raw.split("\n")) {
    if (!line.toLowerCase().includes(term)) continue;
    const r = parse(line);
    if (!r || r.isSidechain || r.isMeta || r.isCompactSummary || !(r.type === "user" || r.type === "assistant")) continue;
    const t = r.type === "user" ? humanText(textOf(r.message?.content)) : textOf(r.message?.content);
    const i = t.toLowerCase().indexOf(term);
    if (i === -1) continue;
    const from = Math.max(0, i - SNIPPET / 2);
    return t.slice(from, from + SNIPPET).replace(/\s+/g, " ").trim();
  }
  return null;
}

// ------------------------------------------------------------------ reading

const short = (s) => {
  const t = String(s ?? "").replace(/\s+/g, " ").trim();
  return t.length > MAX_COMMAND ? `${t.slice(0, MAX_COMMAND)}…` : t;
};

function toolLine(b, result) {
  const i = b.input ?? {};
  const mcp = /^mcp__(.+?)__(.+)$/.exec(b.name ?? "");
  const what = mcp
    ? `called ${mcp[1]}.${mcp[2]}`
    : ({
        Bash: () => `ran: ${short(i.command)}`,
        PowerShell: () => `ran: ${short(i.command)}`,
        Edit: () => `edited: ${short(i.file_path)}`,
        MultiEdit: () => `edited: ${short(i.file_path)}`,
        Write: () => `wrote: ${short(i.file_path)}`,
        NotebookEdit: () => `edited: ${short(i.notebook_path)}`,
        Read: () => `read: ${short(i.file_path)}`,
        Grep: () => `searched files for: ${short(i.pattern)}`,
        Glob: () => `listed files: ${short(i.pattern)}`,
        WebSearch: () => `searched the web: ${short(i.query)}`,
        WebFetch: () => `fetched: ${short(i.url)}`,
        Agent: () => `started a subagent: ${short(i.description)}`,
        Task: () => `started a subagent: ${short(i.description)}`,
      }[b.name]?.() ?? `used ${b.name}`);
  const outcome = !result ? "no result recorded (an attempt)" : result.error ? "failed" : "done";
  return `${what} (${outcome})`;
}

// The whole session as units, oldest first, and its line count. A unit's key
// is the earliest line of the records it is made of, so a cursor that sits on
// it leaves none of them for the next page.
export function claudeUnits(file) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  if (lines.at(-1) === "") lines.pop();
  const units = [];
  const results = new Map(); // tool_use id -> { error }
  const groups = new Map(); // assistant message id -> unit
  const at = (r) => (r.timestamp ? Date.parse(r.timestamp) || null : null);
  lines.forEach((line, i) => {
    const r = parse(line);
    if (!r) return void units.push({ key: i, kind: "drop:unreadable records" });
    if (r.type !== "user" && r.type !== "assistant" && r.type !== "attachment") return; // metadata
    if (r.isSidechain) return void units.push({ key: i, kind: "drop:subagent records" });
    if (r.type === "attachment") {
      const a = r.attachment;
      if (a?.type === "queued_command" && (a.origin?.kind === "human" || a.humanTurn) && typeof a.prompt === "string")
        units.push({ key: i, kind: "user", at: at(r), text: humanText(a.prompt), midTurn: true });
      return;
    }
    if (r.type === "user") {
      const c = r.message?.content;
      for (const b of Array.isArray(c) ? c : []) if (b.type === "tool_result") results.set(b.tool_use_id, { error: !!b.is_error });
      if (r.isCompactSummary) return void units.push({ key: i, kind: "drop:compaction summaries" });
      const raw = textOf(c);
      const images = Array.isArray(c) ? c.filter((b) => b.type === "image").length : 0;
      if (!raw.trim() && !images) return; // tool results only
      const t = humanText(raw);
      if (r.isMeta || (!t && !images)) return void units.push({ key: i, kind: "drop:the app's own notices" });
      units.push({ key: i, kind: "user", at: at(r), text: [t, ...Array(images).fill("[image]")].filter(Boolean).join("\n") });
      return;
    }
    // assistant: one API message can span several records (one per block)
    const id = r.message?.id ?? `line${i}`;
    for (const b of r.message?.content ?? []) {
      if (b.type === "thinking" || b.type === "redacted_thinking") {
        units.push({ key: i, kind: "drop:thinking" });
        continue;
      }
      if (b.type !== "text" && b.type !== "tool_use") continue;
      let g = groups.get(id);
      if (!g) {
        g = { key: i, kind: "final", at: at(r), text: "", uses: [] };
        groups.set(id, g);
        units.push(g);
      }
      if (b.type === "text" && b.text?.trim()) g.text = g.text ? `${g.text}\n${b.text}` : b.text;
      if (b.type === "tool_use") g.uses.push(b);
    }
  });
  // An answer that ends a turn: no tool step in it, and no assistant unit
  // after it before the next user message. Anything else is between steps.
  let later = false;
  for (let j = units.length - 1; j >= 0; j--) {
    const u = units[j];
    if (u.kind === "user") later = false;
    else if (u.uses) {
      u.tools = u.uses.map((b) => toolLine(b, results.get(b.id)));
      u.kind = !u.text ? "tool" : u.uses.length || later ? "interim" : "final";
      delete u.uses;
      later = true;
    }
  }
  units.sort((a, b) => a.key - b.key);
  return { units, lines: lines.length };
}

// Units newest first, older than `before` (a line), as { unit, pos }
export function* claudeStream(units, before) {
  for (let j = units.length - 1; j >= 0; j--) if (before === undefined || units[j].key < before) yield { unit: units[j], pos: units[j].key };
}

export function claudeSession(id) {
  return claudeSessions().find((s) => s.id === id) ?? null;
}

// One page of a session, older than `resume` (a line) when given:
// { meta, page, total }, or { moved: true } when that line is no longer a
// unit's (the file was cut or rewritten)
export async function readClaudePage(s, { resume, limit, includeTools }) {
  const { units, lines } = claudeUnits(s.file);
  if (resume !== undefined && !(resume < lines && units.some((u) => u.key === resume))) return { moved: true };
  const page = await assemble(claudeStream(units, resume), { limit, includeTools });
  return { meta: claudeMeta(s), page, total: units.filter((u) => visible(u, includeTools)).length };
}
