// Claude Code sessions stored on this computer, for bridge_read_chat: found by
// title or folder, and read as units (see src/readchat.mjs).
//
// <claude config dir>/projects/<folder key>/<session id>.jsonl, one record
// per line, append-only. The title the user set is in <folder key>/<session
// id>/custom-title.json and in "custom-title" records (the last one wins);
// without one, an automatic title is in "ai-title" records. A session moved to
// another folder (a worktree) can sit under several folder keys; the newest
// file is the session. The format is Claude Code's own and undocumented: only
// known shapes are read, other records are metadata.
//
// Transcripts can be huge and this runs in the MCP server, which may also own
// the broker: files are read in chunks from the end, asynchronously, never
// whole. A record over MAX_RECORD isn't held in memory or parsed.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { claudeConfigDir } from "./platform.mjs";
import { normalizeName, inFolder, MAX_COMMAND, MAX_MESSAGE, assemble } from "./readchat.mjs";

const CHUNK = 256 * 1024;
export const MAX_RECORD = 8 * 1024 * 1024;
const META_BYTES = 4 * 1024 * 1024; // from the end, for a session's title and folder
const HEAD_BYTES = 1024 * 1024; // from the start, for an untitled session's first message
const TITLE_LINE = 64 * 1024; // a line this long or shorter is looked at whole for a title
const MARK_OVERLAP = 1024; // kept between chunks when looking through a longer one
const MAX_TITLE_MEMO = 5_000;
const ID_BYTES = 4096; // sampled at each end of what a memo has read
const TITLE_FILE_BYTES = 64 * 1024;
export const PAGE_BYTES = 64 * 1024 * 1024; // read for one page before it ends early
const RESULTS_BYTES = 2 * 1024 * 1024; // past a cursor, for the results of the tool steps before it
const MAX_TOOL_LINES = 200;
const EDGE_BYTES = 64 * 1024; // what identifies a record too large to keep
const HEADER_MS = 5_000; // for a page's title, if it isn't settled yet

// Claude Code's own blocks in user turns: reminders and notices it adds,
// sometimes before the user's own words in the same message. They are taken
// out and the rest kept; a message with nothing else is the app's own.
const INJECTED = /<(task-notification|local-command-[a-z]+|command-(?:name|message|args)|system-reminder)\b[^>]*>[\s\S]*?<\/\1>/g;
const CAVEAT = /^\s*Caveat: The messages below were generated by the user while running local commands[^\n]*\n?/;
export const humanText = (t) => String(t ?? "").replace(INJECTED, "").replace(CAVEAT, "").trim();

const projectsDir = () => path.join(claudeConfigDir(), "projects");
const gone = (e) => e.code === "ENOENT" || e.code === "ENOTDIR";
const pause = () => new Promise((r) => setImmediate(r));

// What goes wrong with a chat the user didn't ask about is reported by count
// and reason: its path is no business of the agent reading another chat.
const UNREADABLE = "unreadable";
const TITLE_UNSETTLED = "title not settled";
const FOLDER_UNSETTLED = "folder not found within the limit";

// Every session, newest first, one file per session id, and what couldn't
// be read. No projects folder at all is no sessions; a folder that can't be
// read is a problem, never taken for an empty one.
export async function scanSessions() {
  const byId = new Map();
  const problems = [];
  let dirs = [];
  try {
    dirs = (await fs.promises.readdir(projectsDir(), { withFileTypes: true })).filter((d) => d.isDirectory());
  } catch (e) {
    if (e.code === "ENOENT") return { sessions: [], problems };
    throw new Error(`can't read the sessions folder (${e.code ?? e.message})`);
  }
  for (const d of dirs) {
    const dir = path.join(projectsDir(), d.name);
    let names = [];
    try {
      names = (await fs.promises.readdir(dir)).filter((f) => f.endsWith(".jsonl"));
    } catch (e) {
      if (!gone(e)) problems.push(UNREADABLE);
      continue;
    }
    for (const f of names) {
      const file = path.join(dir, f);
      let st;
      try {
        st = await fs.promises.stat(file);
      } catch (e) {
        if (!gone(e)) problems.push(UNREADABLE);
        continue;
      }
      if (!st.isFile()) {
        problems.push(UNREADABLE);
        continue;
      }
      const id = f.slice(0, -".jsonl".length);
      const prev = byId.get(id);
      if (!prev || st.mtimeMs > prev.mtime) byId.set(id, { id, file, mtime: st.mtimeMs, size: st.size });
    }
  }
  return { sessions: [...byId.values()].sort((a, b) => b.mtime - a.mtime), problems };
}

export const claudeSessions = async () => (await scanSessions()).sessions;
export const claudeSession = async (id) => (await claudeSessions()).find((s) => s.id === id) ?? null;

const parse = (buf) => {
  try {
    return JSON.parse(buf.toString("utf8"));
  } catch {
    return null;
  }
};

const sha = (...bufs) => {
  const h = crypto.createHash("sha1");
  for (const b of bufs) h.update(b);
  return h.digest("hex").slice(0, 20);
};

// A record too large to keep is known by its length, its first and its last
// bytes; read from the file, so this never holds more than that
async function hugeAnchor(fh, offset, end) {
  const edge = async (at) => {
    const buf = Buffer.alloc(Math.min(EDGE_BYTES, end - offset));
    const { bytesRead } = await fh.read(buf, 0, buf.length, at);
    return buf.subarray(0, bytesRead);
  };
  return sha(await edge(offset), await edge(Math.max(offset, end - EDGE_BYTES)));
}

// The file's records from `start` (a byte position) back to its beginning, as
// { offset, length, raw }. A record over MAX_RECORD has raw null and an
// `anchor` instead: its bytes are never kept. Ends with { budget: true } once
// more than `budget` bytes were read. If that happens inside such a record it
// also gives { skipAt, end, head }: pass skip: { end } with start = skipAt to
// go on, so no record can make one call read without limit.
export async function* reverseRecords(file, { start, budget = Infinity, skip = null } = {}) {
  const fh = await fs.promises.open(file, "r");
  const huge = async (offset, end) => ({ offset, length: end - offset, raw: null, anchor: await hugeAnchor(fh, offset, end) });
  try {
    const size = start ?? (await fh.stat()).size;
    let pos = size;
    let carry = Buffer.alloc(0);
    let skipping = !!skip;
    let recordEnd = skip?.end ?? null;
    while (pos > 0) {
      const from = Math.max(0, pos - CHUNK);
      const chunk = Buffer.alloc(pos - from);
      await fh.read(chunk, 0, chunk.length, from);
      pos = from;
      await pause();
      let body = chunk;
      if (skipping) {
        const nl = chunk.lastIndexOf(10);
        if (nl === -1) {
          // (at the very start of the file there is nothing left to go on with)
          if (size - pos > budget && pos > 0) return void (yield { budget: true, skipAt: pos, end: recordEnd, head: chunk.subarray(0, EDGE_BYTES) });
          continue;
        }
        yield await huge(from + nl + 1, recordEnd);
        skipping = false;
        body = chunk.subarray(0, nl + 1);
        carry = Buffer.alloc(0);
      }
      const all = carry.length ? Buffer.concat([body, carry]) : body;
      let end = all.length;
      while (end > 0) {
        const nl = all.lastIndexOf(10, end - 1);
        if (nl === -1) break;
        if (end > nl + 1) {
          const length = end - nl - 1;
          if (length > MAX_RECORD) yield await huge(from + nl + 1, from + end);
          else yield { offset: from + nl + 1, length, raw: all.subarray(nl + 1, end) };
          if (size - pos > budget) return void (yield { budget: true });
        }
        end = nl;
      }
      carry = Buffer.from(all.subarray(0, end));
      if (carry.length > MAX_RECORD) {
        skipping = true;
        recordEnd = from + carry.length;
        carry = Buffer.alloc(0);
      }
    }
    if (skipping) yield await huge(0, recordEnd);
    else if (carry.length) yield { offset: 0, length: carry.length, raw: carry };
  } finally {
    await fh.close();
  }
}

const textOf = (content) =>
  typeof content === "string"
    ? content
    : (content ?? [])
        .filter((b) => b.type === "text")
        .map((b) => b.text)
        .join("\n");

async function readTitleFile(s) {
  const file = path.join(path.dirname(s.file), s.id, "custom-title.json");
  let fh;
  try {
    fh = await fs.promises.open(file, "r");
    const buf = Buffer.alloc(TITLE_FILE_BYTES + 1);
    const { bytesRead } = await fh.read(buf, 0, buf.length, 0);
    if (bytesRead > TITLE_FILE_BYTES) throw new Error("too large");
    return JSON.parse(buf.toString("utf8", 0, bytesRead)).customTitle ?? null;
  } catch (e) {
    // no title file is common; one that can't be read might hold the name asked for
    if (gone(e)) return null;
    throw new Error(UNREADABLE);
  } finally {
    await fh?.close();
  }
}

// The first thing the user wrote, within the first part of the file. Only a
// label for a session with no title, so not finding it hides no name.
async function firstMessage(s) {
  const fh = await fs.promises.open(s.file, "r");
  try {
    const buf = Buffer.alloc(Math.min(HEAD_BYTES, s.size));
    await fh.read(buf, 0, buf.length, 0);
    let start = 0;
    for (;;) {
      const nl = buf.indexOf(10, start);
      if (nl === -1) return null;
      const r = parse(buf.subarray(start, nl));
      start = nl + 1;
      if (r?.type === "user" && !r.isSidechain && !r.isMeta && !r.isCompactSummary) {
        const t = humanText(textOf(r.message?.content));
        if (t) return t;
      }
    }
  } finally {
    await fh.close();
  }
}

// ---------------------------------------------------------------- memos

// A memo of what was read from a file may be used again only for the same
// file, grown at most. Transcripts are append-only: that is an assumption, and
// a rewrite that both grows the file and keeps both sampled regions isn't
// detected. The samples are no check of the whole file.
async function sample(fh, offset, length) {
  const buf = Buffer.alloc(length);
  const { bytesRead } = await fh.read(buf, 0, length, offset);
  return sha(buf.subarray(0, bytesRead));
}

async function fileIdentity(fh, st, frontier) {
  const headLen = Math.min(ID_BYTES, frontier);
  const lastLen = Math.min(ID_BYTES, frontier);
  return {
    dev: st.dev,
    ino: st.ino,
    size: st.size,
    mtime: st.mtimeMs,
    frontier,
    headLen,
    head: await sample(fh, 0, headLen),
    lastLen,
    last: await sample(fh, frontier - lastLen, lastLen),
  };
}

async function sameFile(fh, st, id) {
  if (st.dev !== id.dev || st.ino !== id.ino || st.size < id.size) return false;
  if (st.size === id.size) return st.mtimeMs === id.mtime;
  return (await sample(fh, 0, id.headLen)) === id.head && (await sample(fh, id.frontier - id.lastLen, id.lastLen)) === id.last;
}

// ---------------------------------------------------------------- titles

// In the raw bytes: quotes inside a JSON string are escaped, so this can't match
// the text of a message. What it finds is only a candidate, checked by parsing.
const TITLE_MARK = /"type"\s*:\s*"(?:custom-title|ai-title)"/;
const TITLE_HINT = Buffer.from('-title"');
const hasMark = (buf) => TITLE_MARK.test(buf.latin1Slice(0, buf.length));

const titleScans = new Map();
export const clearTitleMemo = () => titleScans.clear();

// The titles anywhere in a large session, when its end settled no custom one: a
// forward scan that can stop at any chunk and go on from there next time, and
// that only reads what grew. It settles "no title" only by reaching the end with
// no candidate left unresolved: a candidate that doesn't parse, or one in a line
// over TITLE_LINE, isn't held or parsed there and stays unresolved. Whitespace
// over MARK_OVERLAP long inside a marker, in such a line, isn't looked for: "no
// title" holds for the format the app writes (records of a few hundred bytes),
// not for any JSON. A last line with no newline yet is pending.
// maxChunks is for tests: stop as a deadline would, at an exact place.
export async function deepTitles(s, { deadline = Infinity, maxChunks = Infinity } = {}) {
  const fh = await fs.promises.open(s.file, "r");
  try {
    const st = await fh.stat();
    let e = titleScans.get(s.file);
    if (e && !(await sameFile(fh, st, e.id))) e = null;
    if (e?.complete && e.id.size === st.size) return result(e);
    if (!e) e = { frontier: 0, longLine: false, custom: null, ai: null, unresolved: false, pending: false, complete: false, id: null };
    e.complete = false;
    e.pending = false;
    const check = (line) => {
      if (!hasMark(line)) return;
      const r = parse(line);
      if (!r) e.unresolved = true;
      else if (r.type === "custom-title" && r.customTitle) e.custom = r.customTitle;
      else if (r.type === "ai-title" && r.aiTitle) e.ai = r.aiTitle;
    };
    let pos = e.frontier;
    let inLong = e.longLine;
    let carry = Buffer.alloc(0);
    let chunks = 0;
    const chunk = Buffer.allocUnsafe(CHUNK);
    let stopped = false;
    while (pos < st.size) {
      if (Date.now() > deadline || chunks >= maxChunks) {
        stopped = true;
        break;
      }
      chunks++;
      const { bytesRead } = await fh.read(chunk, 0, Math.min(CHUNK, st.size - pos), pos);
      if (!bytesRead) break;
      const fresh = chunk.subarray(0, bytesRead);
      const buf = carry.length ? Buffer.concat([carry, fresh]) : fresh;
      const base = pos - carry.length;
      pos += bytesRead;
      let start = 0;
      if (buf.indexOf(TITLE_HINT) === -1) {
        const nl = buf.lastIndexOf(10);
        if (nl !== -1) {
          start = nl + 1;
          inLong = false;
        }
      } else {
        for (;;) {
          const nl = buf.indexOf(10, start);
          if (nl === -1) break;
          const line = buf.subarray(start, nl);
          if (inLong || line.length > TITLE_LINE) {
            if (hasMark(line)) e.unresolved = true;
          } else check(line);
          inLong = false;
          start = nl + 1;
        }
      }
      const rest = buf.subarray(start);
      if (inLong || rest.length > TITLE_LINE) {
        if (hasMark(rest)) e.unresolved = true;
        inLong = true;
        carry = Buffer.from(rest.subarray(Math.max(0, rest.length - MARK_OVERLAP)));
        e.frontier = pos - carry.length;
      } else {
        carry = Buffer.from(rest);
        e.frontier = base + start;
      }
      e.longLine = inLong;
      await pause();
    }
    if (!stopped) {
      e.complete = true;
      if (!inLong && carry.length && hasMark(carry)) e.pending = true;
    }
    e.id = await fileIdentity(fh, st, e.frontier);
    titleScans.delete(s.file);
    titleScans.set(s.file, e);
    if (titleScans.size > MAX_TITLE_MEMO) titleScans.delete(titleScans.keys().next().value);
    return result(e);
  } finally {
    await fh.close();
  }
}
const result = (e) => ({ custom: e.custom, ai: e.ai, settled: e.complete && !e.unresolved && !e.pending, complete: e.complete, scanned: e.frontier });

// Title and folder. The end of the file settles most (titles are written again
// and again, and most records carry the folder); a custom title in it settles
// the name, whatever lies further back. A large session with none there is
// searched whole, if its folder is in scope. `titleKnown`/`folderKnown` say
// whether they were settled: if not, a name found may not be its name.
export async function claudeMeta(s, { deadline = Infinity, inScope = () => true } = {}) {
  let custom = await readTitleFile(s);
  let ai = null;
  let folder = null;
  let scannedAll = true;
  let unresolved = false;
  if (s.size > 0)
    for await (const rec of reverseRecords(s.file, { budget: META_BYTES })) {
      if (rec.budget) {
        scannedAll = false;
        break;
      }
      if (custom && folder) break;
      if (!rec.raw) continue;
      const r = parse(rec.raw);
      if (!r) {
        if (hasMark(rec.raw)) unresolved = true;
        continue;
      }
      if (!custom && r.type === "custom-title" && r.customTitle) custom = r.customTitle;
      if (!ai && r.type === "ai-title" && r.aiTitle) ai = r.aiTitle;
      if (!folder && typeof r.cwd === "string") folder = r.cwd;
    }
  let titleKnown = !!custom || (scannedAll && !unresolved);
  if (!custom && !scannedAll) {
    if (inScope(folder)) {
      const d = await deepTitles(s, { deadline });
      custom = d.custom;
      ai ??= d.ai;
      titleKnown = !!custom || d.settled;
    } else titleKnown = false;
  }
  let name = custom ?? ai;
  if (!name) {
    const first = await firstMessage(s);
    name = first ? `(untitled) ${first.replace(/\s+/g, " ").slice(0, 60)}` : "(untitled)";
  }
  return { app: "claude", id: s.id, name, folder, updated: s.mtime, titleKnown, folderKnown: !!folder || scannedAll };
}

// ------------------------------------------------------------------ finding

// By title and/or folder, over every session, newest first. A session in scope
// whose title or folder couldn't be settled is reported, whether or not what is
// known of it matches, and so is one the deadline didn't reach: then the search
// isn't complete. A session known to lie outside the folder asked for is out,
// settled or not.
export async function findClaude({ name, folder, add, deadline = Infinity }) {
  const { sessions, problems } = await scanSessions();
  const want = name ? normalizeName(name) : null;
  let looked = 0;
  for (const s of sessions) {
    if (Date.now() > deadline) break;
    looked++;
    try {
      const { titleKnown, folderKnown, ...chat } = await claudeMeta(s, { deadline, inScope: (f) => !folder || !f || inFolder(f, folder) });
      if (folder && !folderKnown) problems.push(FOLDER_UNSETTLED);
      if (folder && folderKnown && !inFolder(chat.folder, folder)) continue;
      if (want && !titleKnown) problems.push(TITLE_UNSETTLED);
      if (folder && !inFolder(chat.folder, folder)) continue;
      if (want && !normalizeName(chat.name).includes(want)) continue;
      add(chat);
    } catch (e) {
      // deleted meanwhile is gone; anything else might have been a match
      if (!gone(e)) problems.push(UNREADABLE);
    }
  }
  const reached = looked >= sessions.length;
  return {
    complete: reached && !problems.length,
    problems,
    scope: `${looked} of ${sessions.length} sessions${reached ? "" : ", the newest (time limit reached)"}`,
  };
}

// ------------------------------------------------------------------ reading

const short = (s) => {
  const t = String(s ?? "").replace(/\s+/g, " ").trim();
  return t.length > MAX_COMMAND ? `${t.slice(0, MAX_COMMAND)}…` : t;
};

function toolLine(b, result) {
  const i = b.input ?? {};
  const mcp = /^mcp__(.+?)__(.+)$/.exec(b.name ?? "");
  const what = mcp
    ? `called ${mcp[1]}.${mcp[2]}`
    : ({
        Bash: () => `ran: ${short(i.command)}`,
        PowerShell: () => `ran: ${short(i.command)}`,
        Edit: () => `edited: ${short(i.file_path)}`,
        MultiEdit: () => `edited: ${short(i.file_path)}`,
        Write: () => `wrote: ${short(i.file_path)}`,
        NotebookEdit: () => `edited: ${short(i.notebook_path)}`,
        Read: () => `read: ${short(i.file_path)}`,
        Grep: () => `searched files for: ${short(i.pattern)}`,
        Glob: () => `listed files: ${short(i.pattern)}`,
        WebSearch: () => `searched the web: ${short(i.query)}`,
        WebFetch: () => `fetched: ${short(i.url)}`,
        Agent: () => `started a subagent: ${short(i.description)}`,
        Task: () => `started a subagent: ${short(i.description)}`,
      }[b.name]?.() ?? `used ${b.name}`);
  const outcome = !result ? "no result seen (an attempt)" : result.error ? "failed" : "done";
  return `${what} (${outcome})`;
}

const noteResults = (r, results) => {
  const c = r?.message?.content;
  if (r?.type === "user" && Array.isArray(c)) for (const b of c) if (b.type === "tool_result") results.set(b.tool_use_id, { error: !!b.is_error });
};

// A cursor's results lie just after it: the tool steps on the next page can
// have their results in records already passed
async function resultsAfter(file, offset) {
  const results = new Map();
  const fh = await fs.promises.open(file, "r");
  try {
    const buf = Buffer.alloc(RESULTS_BYTES);
    const { bytesRead } = await fh.read(buf, 0, buf.length, offset);
    let start = 0;
    for (;;) {
      const nl = buf.indexOf(10, start);
      if (nl === -1 || nl >= bytesRead) break;
      noteResults(parse(buf.subarray(start, nl)), results);
      start = nl + 1;
    }
  } finally {
    await fh.close();
  }
  return results;
}

// A record as a cursor knows it: where it starts, how long it is, and a hash
// of all of it (or, for a huge one, of its two ends)
const recordPos = (rec) => ({ o: rec.offset, n: rec.length, h: rec.raw ? sha(rec.raw) : rec.anchor });

// Is that position still the same record, whole (or, inside a huge one, the
// same bytes)? A shifted or rewritten file fails this; records added at the
// end don't touch it.
async function boundaryHolds(file, { o, h, n, s: inside }) {
  const fh = await fs.promises.open(file, "r");
  try {
    const { size } = await fh.stat();
    if (o >= size) return false;
    const at = async (offset, length) => {
      const buf = Buffer.alloc(length);
      const { bytesRead } = await fh.read(buf, 0, length, offset);
      return buf.subarray(0, bytesRead);
    };
    if (inside) return sha(await at(o, EDGE_BYTES)) === h;
    if (o > 0 && (await at(o - 1, 1))[0] !== 10) return false;
    if (o + n > size) return false;
    if (o + n < size && (await at(o + n, 1))[0] !== 10) return false;
    return (n > MAX_RECORD ? await hugeAnchor(fh, o, o + n) : sha(await at(o, n))) === h;
  } finally {
    await fh.close();
  }
}

// A session's units, newest first, as { unit, pos }, or { budget: true, pos }
// when the read budget ran out. pos is what a cursor stores: { o, n, h } for
// the record it sits on, l for whether an assistant message follows in that
// turn (which is what makes an earlier one a step, not the answer), s and e
// for a place inside a huge record, and m for the message whose earlier
// records are being passed over.
//
// Records of one assistant message are merged into one unit, however far
// apart, and shown only whole. Things dropped in between are reported right
// after it, so no cursor can fall inside a message. If the budget runs out in
// one, the page ends before it and the next call starts there with a fresh
// budget; a message spread wider than a whole budget is left out and said so.
export async function* claudeStream(file, resume, { includeTools = true, budget = PAGE_BYTES } = {}) {
  const results = resume && includeTools ? await resultsAfter(file, resume.o) : new Map();
  let later = resume?.l ?? false;
  let passing = resume?.m ?? null;
  let open = null;
  let pending = [];
  let last = null; // the last record read, shown or not
  const at = (r) => (r.timestamp ? Date.parse(r.timestamp) || null : null);
  const posOf = (rec) => ({ ...recordPos(rec), l: later, ...(passing && { m: passing }) });
  const flush = () => {
    const steps = [];
    if (open) {
      const { uses, at: when, text, moreTools, pos: start } = open;
      const kind = !text ? "tool" : uses.length || later ? "interim" : "final";
      later = true;
      const pos = { ...start, l: later };
      steps.push({ unit: { kind, at: when, text, moreTools, tools: uses.map((b) => toolLine(b, results.get(b.id))) }, pos });
      for (const k of pending) steps.push({ unit: { kind: k }, pos });
    }
    open = null;
    pending = [];
    return steps;
  };
  const dropped = function* (kind, rec) {
    if (open) pending.push(kind);
    else yield { unit: { kind }, pos: posOf(rec) };
  };
  for await (const rec of reverseRecords(file, { start: resume?.o, budget, skip: resume?.s ? { end: resume.e } : null })) {
    if (rec.budget) {
      const inside = rec.skipAt !== undefined ? { o: rec.skipAt, n: 0, h: sha(rec.head), s: true, e: rec.end, l: later, ...(passing && { m: passing }) } : null;
      if (open?.before) yield { budget: true, pos: posOf(open.before) };
      else if (open) {
        // nothing before it in this call: it alone used up the budget
        const pos = { ...(inside ?? posOf(last)), l: true, m: open.id };
        yield { unit: { kind: "drop:messages spread too far to read" }, pos };
        yield { budget: true, pos };
      } else yield { budget: true, pos: inside ?? posOf(last) };
      return;
    }
    const previous = last;
    last = rec;
    if (!rec.raw) {
      yield* dropped("drop:records too large to read", rec);
      continue;
    }
    const r = parse(rec.raw);
    if (!r) {
      yield* dropped("drop:unreadable records", rec);
      continue;
    }
    if (r.type !== "user" && r.type !== "assistant" && r.type !== "attachment") continue; // metadata
    if (r.isSidechain) {
      yield* dropped("drop:subagent records", rec);
      continue;
    }
    if (r.type === "attachment") {
      const a = r.attachment;
      if (a?.type === "queued_command" && (a.origin?.kind === "human" || a.humanTurn) && typeof a.prompt === "string") {
        yield* flush();
        later = false;
        passing = null;
        yield { unit: { kind: "user", at: at(r), text: humanText(a.prompt), midTurn: true }, pos: posOf(rec) };
      }
      continue;
    }
    if (r.type === "user") {
      noteResults(r, results);
      const c = r.message?.content;
      if (r.isCompactSummary) {
        yield* dropped("drop:compaction summaries", rec);
        continue;
      }
      const raw = textOf(c);
      const images = Array.isArray(c) ? c.filter((b) => b.type === "image").length : 0;
      if (!raw.trim() && !images) continue; // tool results only
      const t = humanText(raw);
      if (r.isMeta || (!t && !images)) {
        yield* dropped("drop:the app's own notices", rec);
        continue;
      }
      yield* flush();
      later = false;
      passing = null;
      yield { unit: { kind: "user", at: at(r), text: [t, ...Array(images).fill("[image]")].filter(Boolean).join("\n") }, pos: posOf(rec) };
      continue;
    }
    // assistant: one API message can span several records (one per block)
    const id = r.message?.id ?? `at${rec.offset}`;
    if (passing === id) continue; // the rest of a message already left out
    passing = null;
    if (open && open.id !== id) yield* flush();
    for (const b of [...(r.message?.content ?? [])].reverse()) {
      if (b.type === "thinking" || b.type === "redacted_thinking") {
        yield* dropped("drop:thinking", rec);
        continue;
      }
      if (b.type === "text" ? !b.text?.trim() : b.type !== "tool_use") continue;
      if (!open) open = { id, uses: [], text: "", at: at(r), moreTools: 0, before: previous };
      open.pos = recordPos(rec);
      open.at = at(r) ?? open.at;
      if (b.type === "text") open.text = (open.text ? `${b.text}\n${open.text}` : b.text).slice(0, MAX_MESSAGE + 1); // one over, so the cut is noticed
      if (b.type === "tool_use") {
        open.uses.unshift(b);
        if (open.uses.length > MAX_TOOL_LINES) {
          open.uses.pop();
          open.moreTools++;
        }
      }
    }
  }
  yield* flush();
}

// One page of a session, older than `resume` when given: { meta, page }, or
// { moved: true } when the position no longer holds the same record
export async function readClaudePage(s, { resume, limit, includeTools, budget }) {
  if (resume && !(await boundaryHolds(s.file, resume))) return { moved: true };
  const page = await assemble(claudeStream(s.file, resume, { includeTools, budget }), { limit, includeTools });
  return { meta: await claudeMeta(s, { deadline: Date.now() + HEADER_MS }), page };
}
