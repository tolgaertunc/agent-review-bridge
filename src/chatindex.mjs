// A Claude Code session as a graph, for bridge_read_chat: which records make up
// the conversation as it stands now, and which were left behind.
//
// A transcript isn't a list. A rewind leaves the old branch in the file, parallel
// tool calls fork on purpose, a record can be written twice. So a read scans the
// file once into a small index (never the file's text), computes the current
// branch from it, and pages by position in that result. The scan is streamed,
// can stop at any chunk and go on from that byte, yields to the event loop, and
// only reads what grew since last time. A whole scan because telling a late copy
// from a leaf takes knowing every record's children, which no read of a part of
// the file can.
//
// The rules follow the Agent SDK's reader, except that compaction is followed
// back through logicalParentUuid: this tool reads the original history and leaves
// that compaction's summary out, where the SDK shows the summary instead. Where the
// history before a compaction can't be followed (no logical parent, one that comes
// back round to the boundary, or a break further back in what it leads to), the
// summary is shown in its place, as the SDK does, and the page says so.

import fs from "node:fs";
import crypto from "node:crypto";

export const CHUNK = 256 * 1024;
export const MAX_RECORD = 8 * 1024 * 1024; // a longer line is never held or parsed
export const SCAN_MS = 20_000; // scanning per call; not a limit on the whole call
export const MAX_SESSION_BYTES = 128 * 1024 * 1024; // what an index may hold
export const MAX_MEMO_BYTES = 192 * 1024 * 1024; // what all of them may hold
const MAX_MEMO = 2;
const ID_BYTES = 4096; // sampled at each end of what a memo has read
const BATCH = 10_000; // records between yields while resolving
const CAP = 256; // what the tokenizer keeps of a top-level string

// What the index's own bookkeeping costs per record, beyond its strings. Checked
// against the real heap in scripts/test-chat-graph.mjs.
const REC_BYTES = 240;
const STR_BYTES = 40;

export const pause = () => new Promise((r) => setImmediate(r));

export const sha = (...bufs) => {
  const h = crypto.createHash("sha1");
  for (const b of bufs) h.update(b);
  return h.digest("hex").slice(0, 20);
};

export const parse = (buf) => {
  try {
    return JSON.parse(buf.toString("utf8"));
  } catch {
    return null;
  }
};

export const textOf = (content) =>
  typeof content === "string"
    ? content
    : Array.isArray(content)
      ? content
          .filter((b) => b?.type === "text")
          .map((b) => b.text)
          .join("\n")
      : "";

// Claude Code's own blocks in user turns: reminders and notices it adds,
// sometimes before the user's own words in the same message. They are taken
// out and the rest kept; a message with nothing else is the app's own.
const INJECTED = /<(task-notification|local-command-[a-z]+|command-(?:name|message|args)|system-reminder|ide_opened_file|ide_selection)\b[^>]*>[\s\S]*?<\/\1>/g;
const CAVEAT = /^\s*Caveat: The messages below were generated by the user while running local commands[^\n]*\n?/;
export const humanText = (t) => String(t ?? "").replace(INJECTED, "").replace(CAVEAT, "").trim();

export const humanQueued = (a) => a?.type === "queued_command" && (a.origin?.kind === "human" || a.humanTurn) && typeof a.prompt === "string";

// ------------------------------------------------------------ the same file?

// A memo of what was read from a file may be used again only for the same file,
// grown at most. Transcripts are append-only: that is an assumption, and a rewrite
// that both grows the file and keeps both sampled regions isn't detected. The
// samples are no check of the whole file.
async function sample(fh, offset, length) {
  const buf = Buffer.alloc(length);
  const { bytesRead } = await fh.read(buf, 0, length, offset);
  return sha(buf.subarray(0, bytesRead));
}

export async function fileIdentity(fh, st, frontier) {
  const len = Math.min(ID_BYTES, frontier);
  return { dev: st.dev, ino: st.ino, size: st.size, mtime: st.mtimeMs, frontier, len, head: await sample(fh, 0, len), last: await sample(fh, frontier - len, len) };
}

export async function sameFile(fh, st, id) {
  if (st.dev !== id.dev || st.ino !== id.ino || st.size < id.size) return false;
  if (st.size === id.size) return st.mtimeMs === id.mtime;
  return (await sample(fh, 0, id.len)) === id.head && (await sample(fh, id.frontier - id.len, id.len)) === id.last;
}

// -------------------------------------------------------------- the tokenizer

const WS = (c) => c === 32 || c === 10 || c === 13 || c === 9;
const WANTED = new Set(["type", "subtype", "uuid", "parentUuid", "logicalParentUuid", "isSidechain", "isMeta", "teamName"]);
export const MALFORMED = Symbol("malformed");

// The top-level fields of a JSON object too long to hold, from its bytes, fed in
// pieces. Only depth-1 keys count, so a nested "uuid" or one inside a string can't
// be taken for the record's. A field present with a value of the wrong kind is
// MALFORMED, an absent one undefined, and an explicit null is null, so no edge of
// the graph is invented. finish() is null if it wasn't one whole object.
export class TopFields {
  fields = {};
  depth = 0;
  inStr = false;
  esc = false;
  bad = false;
  ended = false;
  expect = "key";
  key = null;
  cap = null;
  over = false;
  capFor = null;
  lit = null;
  feed(buf) {
    if (this.bad) return;
    for (let i = 0; i < buf.length; i++) {
      const c = buf[i];
      if (this.inStr) {
        if (this.esc) {
          this.esc = false;
          this.keep(c);
        } else if (c === 92) {
          this.esc = true;
          this.keep(c);
        } else if (c === 34) {
          this.inStr = false;
          this.endString();
        } else this.keep(c);
        continue;
      }
      if (this.lit) {
        if (WS(c) || c === 44 || c === 125 || c === 93) this.endLiteral();
        else {
          if (this.lit.length < 16) this.lit.push(c);
          continue;
        }
      }
      if (WS(c)) continue;
      if (this.depth === 0) {
        if (this.ended || c !== 123) return void (this.bad = true);
        this.depth = 1;
        this.expect = "first";
        continue;
      }
      if (this.depth > 1) {
        if (c === 34) {
          this.inStr = true;
          this.capFor = null;
        } else if (c === 123 || c === 91) this.depth++;
        else if (c === 125 || c === 93) {
          if (--this.depth === 1) this.expect = "comma";
        }
        continue;
      }
      switch (this.expect) {
        case "first":
        case "key":
          if (c === 34) {
            this.begin("key");
          } else if (c === 125 && this.expect === "first") this.close();
          else return void (this.bad = true);
          break;
        case "colon":
          if (c !== 58) return void (this.bad = true);
          this.expect = "value";
          break;
        case "value":
          if (c === 34) this.begin("value");
          else if (c === 123 || c === 91) {
            this.set(MALFORMED);
            this.depth = 2;
          } else {
            this.lit = [c];
          }
          break;
        case "comma":
          if (c === 44) this.expect = "key";
          else if (c === 125) this.close();
          else return void (this.bad = true);
          break;
      }
    }
  }
  begin(what) {
    this.inStr = true;
    this.capFor = what;
    this.cap = [];
    this.over = false;
  }
  keep(c) {
    if (!this.capFor) return;
    if (this.cap.length < CAP) this.cap.push(c);
    else this.over = true;
  }
  decoded() {
    try {
      return JSON.parse(`"${Buffer.from(this.cap).toString("utf8")}"`);
    } catch {
      return MALFORMED;
    }
  }
  endString() {
    const what = this.capFor;
    this.capFor = null;
    if (what === "key") {
      this.key = this.over ? null : this.decoded();
      this.expect = "colon";
    } else if (what === "value") {
      this.set(this.over ? MALFORMED : this.decoded());
      this.expect = "comma";
    }
    this.cap = null;
  }
  endLiteral() {
    const t = Buffer.from(this.lit).toString("latin1");
    this.lit = null;
    this.set(t === "null" ? null : t === "true" ? true : t === "false" ? false : MALFORMED);
    this.expect = "comma";
  }
  set(v) {
    if (WANTED.has(this.key)) this.fields[this.key] = v;
  }
  close() {
    this.depth = 0;
    this.ended = true;
  }
  finish() {
    if (this.lit) this.bad = true;
    return this.bad || !this.ended || this.inStr ? null : this.fields;
  }
}

// ------------------------------------------------------------------ the index

export const F = {
  CONV: 1, // user or assistant
  HUMAN: 2, // what the user wrote
  QUEUED: 4, // what the user wrote while a turn ran
  TEXT: 8,
  USE: 16,
  THINK: 32,
  NOTICE: 64, // the app's own
  SUMMARY: 128,
  RESULT: 256,
  API_ERROR: 512,
  META: 1024,
  TEAM: 2048,
  SIDE: 4096,
  HUGE: 8192,
  BOUNDARY: 16384,
};

// Why something isn't shown
export const R = {
  SUBAGENT: "subagent records",
  NOTICE: "the app's own notices",
  SUMMARY: "compaction summaries",
  THINKING: "thinking",
  OTHER_BRANCH: "messages on a branch that was rewound or left",
  UNREADABLE: "unreadable records",
  HUGE: "records too large to read",
};

const size = (rec) => REC_BYTES + rec.u.length + (rec.m ? STR_BYTES + rec.m.length : 0) + (rec.src ? STR_BYTES + rec.src.length : 0) + (rec.uses?.length ?? 0) * (STR_BYTES + 40) + (rec.res?.length ?? 0) * (STR_BYTES + 60);

class SessionIndex {
  records = new Map(); // uuid → the newest copy; in file order of those copies
  unreadable = [];
  unparsedHuge = [];
  pos = 0;
  lineStart = 0;
  parts = [];
  partLen = 0;
  tok = null;
  bytes = 0;
  version = 0;
  id = null;
  view = null;
  viewVersion = -1;
  viewBytes = 0;
  tooLarge = false;
  busy = Promise.resolve();
  constructor(file, maxBytes) {
    this.file = file;
    this.maxBytes = maxBytes;
  }
  retained() {
    return this.bytes + this.partLen + this.viewBytes;
  }
  add(rec) {
    const old = this.records.get(rec.u);
    if (old) {
      this.bytes -= size(old);
      this.records.delete(rec.u); // so the order stays that of the newest copies
    }
    this.records.set(rec.u, rec);
    this.bytes += size(rec);
    this.version++;
  }
  parent(v) {
    if (v === null) return null;
    if (typeof v !== "string") return undefined;
    return this.records.get(v)?.u ?? v;
  }
  addLine(o, line) {
    if (!line.length) return;
    const r = parse(line);
    if (!r || typeof r !== "object") {
      this.unreadable.push(o);
      this.bytes += 8;
      this.version++;
      return;
    }
    const conv = r.type === "user" || r.type === "assistant";
    const queued = r.type === "attachment" && humanQueued(r.attachment);
    if (typeof r.uuid !== "string" && !conv && !queued) return; // metadata
    const rec = { u: typeof r.uuid === "string" ? r.uuid : `@${o}`, o, n: line.length, p: typeof r.uuid === "string" ? this.parent(r.parentUuid) : undefined, f: 0 };
    if (typeof r.logicalParentUuid === "string") rec.l = r.logicalParentUuid;
    if (r.isSidechain) {
      rec.f = F.SIDE;
      return this.add(rec);
    }
    if (r.teamName) rec.f |= F.TEAM;
    if (r.isMeta) rec.f |= F.META;
    if (conv) rec.f |= F.CONV;
    if (r.type === "system" && r.subtype === "compact_boundary") rec.f |= F.BOUNDARY;
    if (typeof r.sourceToolAssistantUUID === "string") rec.src = r.sourceToolAssistantUUID;
    const c = r.message?.content;
    if (r.type === "user") {
      if (Array.isArray(c)) {
        const res = c.filter((b) => b?.type === "tool_result" && typeof b.tool_use_id === "string").map((b) => [b.tool_use_id, !!b.is_error]);
        if (res.length) {
          rec.res = res;
          rec.f |= F.RESULT;
        }
      }
      if (r.isCompactSummary) rec.f |= F.SUMMARY;
      else {
        const raw = textOf(c);
        const images = Array.isArray(c) && c.some((b) => b?.type === "image");
        if (raw.trim() || images) rec.f |= r.isMeta || (!humanText(raw) && !images) ? F.NOTICE : F.HUMAN;
      }
    } else if (r.type === "assistant") {
      rec.m = typeof r.message?.id === "string" ? r.message.id : `at${o}`;
      if (r.isApiErrorMessage) rec.f |= F.API_ERROR;
      if (Array.isArray(c))
        for (const b of c) {
          if (b?.type === "thinking" || b?.type === "redacted_thinking") rec.f |= F.THINK;
          else if (b?.type === "text" && b.text?.trim()) rec.f |= F.TEXT;
          else if (b?.type === "tool_use") {
            rec.f |= F.USE;
            if (typeof b.id === "string") (rec.uses ??= []).push(b.id);
          }
        }
    } else if (queued) rec.f |= humanText(r.attachment.prompt) ? F.QUEUED : F.NOTICE;
    this.add(rec);
  }
  addHuge(o, n, fields) {
    if (!fields) {
      this.unparsedHuge.push(o);
      this.bytes += 8;
      this.version++;
      return;
    }
    const ok = typeof fields.uuid === "string";
    const conv = fields.type === "user" || fields.type === "assistant";
    if (!ok && !conv) {
      this.unparsedHuge.push(o);
      this.bytes += 8;
      this.version++;
      return;
    }
    const rec = { u: ok ? fields.uuid : `@${o}`, o, n, p: ok ? this.parent(fields.parentUuid) : undefined, f: F.HUGE };
    if (typeof fields.logicalParentUuid === "string") rec.l = fields.logicalParentUuid;
    if (fields.isSidechain === true) rec.f |= F.SIDE;
    else {
      if (typeof fields.teamName === "string" && fields.teamName) rec.f |= F.TEAM;
      if (fields.isMeta === true) rec.f |= F.META;
      if (conv) rec.f |= F.CONV;
      if (fields.type === "system" && fields.subtype === "compact_boundary") rec.f |= F.BOUNDARY;
    }
    this.add(rec);
  }
  feed(buf, base) {
    let start = 0;
    while (start < buf.length) {
      const nl = buf.indexOf(10, start);
      if (nl === -1) {
        const rest = buf.subarray(start);
        if (this.tok) this.tok.feed(rest);
        else {
          this.parts.push(Buffer.from(rest));
          this.partLen += rest.length;
          if (this.partLen > MAX_RECORD) {
            this.tok = new TopFields();
            for (const p of this.parts) this.tok.feed(p);
            this.parts = [];
            this.partLen = 0;
          }
        }
        return;
      }
      const piece = buf.subarray(start, nl);
      const end = base + nl;
      if (this.tok) {
        this.tok.feed(piece);
        this.addHuge(this.lineStart, end - this.lineStart, this.tok.finish());
        this.tok = null;
      } else if (this.partLen + piece.length > MAX_RECORD) {
        const tok = new TopFields();
        for (const p of this.parts) tok.feed(p);
        tok.feed(piece);
        this.addHuge(this.lineStart, end - this.lineStart, tok.finish());
        this.parts = [];
        this.partLen = 0;
      } else {
        this.addLine(this.lineStart, this.parts.length ? Buffer.concat([...this.parts, piece]) : piece);
        this.parts = [];
        this.partLen = 0;
      }
      start = nl + 1;
      this.lineStart = base + start;
    }
  }
  // true when it reached the end of the file. A line with no newline yet stays
  // pending, and a stop keeps everything needed to go on from that byte.
  async scan(fh, st, { scanMs, maxChunks, onGrow }) {
    const until = Date.now() + scanMs;
    let chunks = 0;
    const chunk = Buffer.allocUnsafe(CHUNK);
    while (this.pos < st.size) {
      if (Date.now() > until || chunks >= maxChunks) return false;
      chunks++;
      const { bytesRead } = await fh.read(chunk, 0, Math.min(CHUNK, st.size - this.pos), this.pos);
      if (!bytesRead) break;
      this.feed(chunk.subarray(0, bytesRead), this.pos);
      this.pos += bytesRead;
      if (this.bytes > this.maxBytes) {
        this.markTooLarge();
        return true;
      }
      onGrow();
      await pause();
    }
    return true;
  }
  markTooLarge() {
    this.tooLarge = true;
    this.records = new Map();
    this.unreadable = [];
    this.unparsedHuge = [];
    this.parts = [];
    this.partLen = 0;
    this.tok = null;
    this.view = null;
    this.bytes = 0;
    this.viewBytes = 0;
  }
}

// ---------------------------------------------------------------- the branch

const isRec = (x) => x && typeof x === "object";
const BREAK = Symbol("break");

// A call's outcome: a result on the branch itself decides; otherwise others do
// only if they agree. (Apart from resolve, whose scope it would otherwise keep alive.)
const outcomes = (core, others) => (id) => {
  if (core.has(id)) return core.get(id) ? "failed" : "done";
  const seen = others.get(id);
  if (!seen) return null;
  return seen.size > 1 ? "unclear" : seen.has(true) ? "failed" : "done";
};

// The conversation as it stands: { units, branch, omitted, outcome, broke,
// compaction }. compaction is null, or { state: "cut" | "incomplete", summary }
// for the compaction whose earlier history can't be reconstructed, with the key
// of its summary's unit, or null when there's none to show.
// units is newest first, one per message. branch is every record that belongs to
// it, newest first, and a unit's `bi` is its place there. Everything is linear in
// the number of records, and yields as it goes.
export async function resolve(idx) {
  let beat = 0;
  const breathe = async () => {
    if (++beat % BATCH === 0) await pause();
  };
  const by = (u) => {
    const r = idx.records.get(u);
    return r && !(r.f & F.SIDE) ? r : null;
  };
  // A compaction's boundary has no parent; its step back is its logical parent,
  // the history before the compaction. A boundary is cut when that can't be
  // followed: no logical parent is named or found, or following it comes back
  // round to the boundary (a session resumed after a compaction can be written
  // so). The walk stops at a cut boundary as at a root, and its summary stands in
  // for what came before.
  const cut = new Set();
  const compacted = (rec) => rec.p === null && rec.f & F.BOUNDARY;
  // the step back from a record: another record, null at a true root or a cut
  // boundary, BREAK if the history can't be followed from here
  const stepBack = (rec) => {
    if (typeof rec.p === "string") return by(rec.p) ?? BREAK;
    if (rec.p === undefined) return BREAK;
    if (rec.f & F.BOUNDARY) return cut.has(rec) ? null : by(rec.l);
    return null;
  };

  const main = [];
  for (const rec of idx.records.values()) {
    await breathe();
    if (rec.f & F.SIDE) continue;
    main.push(rec);
    if (compacted(rec) && !(typeof rec.l === "string" && by(rec.l))) cut.add(rec);
  }

  // Each record has one step back, so each part of the graph has at most one
  // cycle. One through a boundary's logical parent is cut at every boundary on
  // it: cutting one can leave another pointing back past the newest message, and
  // none of their history goes anywhere but round. Logical parents that only
  // lead into a cycle are kept. A cycle of parentUuids alone stays a break.
  // (The marks go before `near` grows, so the peak stays what viewBytes counts.)
  {
    const mark = new Map(); // place on the path being walked, or -1 once done
    for (const start of main) {
      if (mark.has(start)) continue;
      const path = [];
      let cur = start;
      while (isRec(cur) && !mark.has(cur)) {
        await breathe();
        mark.set(cur, path.length);
        path.push(cur);
        cur = stepBack(cur);
      }
      const at = isRec(cur) ? mark.get(cur) : -1;
      if (at >= 0) for (let i = at; i < path.length; i++) if (compacted(path[i])) cut.add(path[i]);
      for (const r of path) mark.set(r, -1);
    }
  }

  // who has children, by those same steps
  const parents = new Set();
  for (const rec of main) {
    await breathe();
    const back = stepBack(rec);
    if (isRec(back)) parents.add(back);
  }

  // the nearest conversation record at or behind a record: each is walked once
  const isLeaf = (r) => r.f & F.CONV && !(r.f & (F.META | F.TEAM));
  const near = new Map();
  const nearest = (start) => {
    const path = [];
    const onPath = new Set();
    let cur = start;
    let found = null;
    while (isRec(cur)) {
      if (near.has(cur)) {
        found = near.get(cur);
        break;
      }
      if (onPath.has(cur)) break;
      if (isLeaf(cur)) {
        found = cur;
        path.push(cur);
        break;
      }
      path.push(cur);
      onPath.add(cur);
      cur = stepBack(cur);
    }
    for (const r of path) near.set(r, found);
    return found;
  };

  // the leaf: the latest in the file that some terminal record leads to
  let leaf = null;
  for (const rec of main) {
    await breathe();
    if (parents.has(rec)) continue;
    const l = nearest(rec);
    if (l && (!leaf || l.o > leaf.o)) leaf = l;
  }

  // the walk
  const core = [];
  const coreSet = new Set();
  let broke = !leaf;
  // the boundary whose logical parent the walk followed last: a break further
  // back is in the history before that compaction, which then isn't whole. One
  // crossed earlier did reach the next boundary back, so its own history is.
  let crossed = null;
  let cur = leaf;
  while (cur) {
    await breathe();
    core.push(cur);
    coreSet.add(cur);
    const back = stepBack(cur);
    if (back === BREAK || (isRec(back) && coreSet.has(back))) {
      broke = true;
      break;
    }
    if (isRec(back) && compacted(cur)) crossed = cur;
    cur = back;
  }
  // the compaction whose history before it can't be reconstructed, if any: the
  // walk ends either at a cut boundary or at a break, so there is one at most
  const ended = core.at(-1);
  const gap = ended && cut.has(ended) ? { boundary: ended, state: "cut" } : broke && crossed ? { boundary: crossed, state: "incomplete" } : null;

  // what else belongs to the messages on it, wherever it lies in the file: the
  // other records of a parallel call, and their results
  const byMsg = new Map();
  const owners = new Map();
  const AMBIGUOUS = Symbol("ambiguous");
  for (const rec of main) {
    await breathe();
    if (!rec.m) continue;
    let list = byMsg.get(rec.m);
    if (!list) byMsg.set(rec.m, (list = []));
    list.push(rec);
    for (const id of rec.uses ?? []) {
      const had = owners.get(id);
      owners.set(id, had === undefined || had === rec.m ? rec.m : AMBIGUOUS);
    }
  }
  const coreMsgs = new Set(core.filter((r) => r.m).map((r) => r.m));
  const resultsOf = new Map();
  const coreResults = new Map();
  const otherResults = new Map();
  for (const rec of main) {
    await breathe();
    if (!(rec.f & F.RESULT)) continue;
    if (coreSet.has(rec)) {
      for (const [id, err] of rec.res) coreResults.set(id, err);
      continue;
    }
    let owner = null;
    for (const u of [rec.p, rec.src]) {
      const m = typeof u === "string" ? by(u)?.m : null;
      if (m && coreMsgs.has(m)) owner = m;
    }
    for (const [id, err] of rec.res) {
      const m = owners.get(id);
      if (m === AMBIGUOUS || m === undefined) continue;
      if (!owner && coreMsgs.has(m)) owner = m;
      let seen = otherResults.get(id);
      if (!seen) otherResults.set(id, (seen = new Set()));
      seen.add(err);
    }
    if (owner) {
      let list = resultsOf.get(owner);
      if (!list) resultsOf.set(owner, (list = []));
      list.push(rec);
    }
  }
  const outcome = outcomes(coreResults, otherResults);

  // the branch, newest first: what the user typed after the leaf, then the walk,
  // with each message's other records beside its newest one
  const branch = [];
  const inBranch = new Set();
  const put = (r) => {
    if (inBranch.has(r)) return;
    inBranch.add(r);
    branch.push(r);
  };
  const trailing = main.filter((r) => r.f & F.QUEUED && !coreSet.has(r) && leaf && nearest(r) === leaf);
  for (const r of trailing.reverse()) put(r);
  const coreIds = new Set();
  for (const r of core) {
    await breathe();
    if (r.m && !coreIds.has(r.m)) {
      coreIds.add(r.m);
      const extra = [...byMsg.get(r.m), ...(resultsOf.get(r.m) ?? [])].filter((x) => !coreSet.has(x)).sort((a, b) => b.o - a.o);
      for (const x of extra) put(x);
    }
    put(r);
  }

  // past a break, or a cut boundary, nothing is known about how older records
  // relate: all of them are shown, in file order, and none is called abandoned
  const certainEnd = branch.length;
  if (broke || gap?.state === "cut") {
    let low = Infinity;
    for (const r of core) if (r.o < low) low = r.o;
    for (let i = main.length - 1; i >= 0; i--) {
      await breathe();
      const r = main[i];
      if (r.o < low && r.f & (F.CONV | F.QUEUED) && !inBranch.has(r)) put(r);
    }
  }

  // that compaction's summary, which is then shown: the newest is the one named.
  // One too large to read was never parsed, so isn't known to be one: it's
  // counted as too large, and the page says the summary is unavailable.
  const shownSummary = new Set();
  let compaction = null;
  if (gap) {
    let summary = null;
    for (const r of branch) {
      if (!(r.f & F.SUMMARY) || r.f & F.HUGE || r.p !== gap.boundary.u) continue;
      shownSummary.add(r);
      summary ??= r.u;
    }
    compaction = { state: gap.state, summary };
  }

  // one unit per message
  const units = [];
  const unitOfMsg = new Map();
  for (let bi = 0; bi < branch.length; bi++) {
    await breathe();
    const r = branch[bi];
    if (r.f & (F.TEAM | F.HUGE)) continue;
    if (shownSummary.has(r)) {
      units.push({ key: r.u, kind: "summary", members: [r], bi, min: r.o, uncertain: bi >= certainEnd });
    } else if (r.f & (F.HUMAN | F.QUEUED)) {
      units.push({ key: r.u, kind: "user", members: [r], bi, min: r.o, midTurn: !!(r.f & F.QUEUED), uncertain: bi >= certainEnd });
    } else if (r.m && r.f & (F.TEXT | F.USE)) {
      let u = unitOfMsg.get(r.m);
      if (!u) {
        u = { key: r.m, kind: null, members: [], bi, min: r.o, text: false, use: false, uncertain: bi >= certainEnd };
        unitOfMsg.set(r.m, u);
        units.push(u);
      }
      u.members.push(r);
      if (r.o < u.min) u.min = r.o;
      if (r.f & F.TEXT) u.text = true;
      if (r.f & F.USE) u.use = true;
    }
  }

  // what kind each is, by turn: newest to oldest, the first text of a turn is its
  // answer, if nothing came after it. A message typed mid-turn starts a new stretch.
  // In the stretch before it, text with tool steps after it is between steps if the
  // turn ran on past that message, and unfinished if it didn't. Text with nothing
  // after it is an answer either way: the typed message may have been taken up only
  // after that turn had ended, and hiding an answer is the worse mistake.
  let textSeen = false;
  let activity = false;
  let ranOn = false;
  let any = false;
  for (const u of units) {
    // a summary ends the stretch before it, as a message the user sent does
    if (u.kind === "user" || u.kind === "summary") {
      if (u.midTurn) ranOn = ranOn || any;
      else ranOn = false;
      any = false;
      textSeen = false;
      activity = false;
      continue;
    }
    any = true;
    if (!u.text) u.kind = "tool";
    else if (textSeen) u.kind = "interim";
    else {
      textSeen = true;
      u.kind = !u.use && !activity ? "final" : ranOn ? "interim" : "unfinished";
    }
    if (u.use) activity = true;
  }

  // what isn't shown, by reason, each in file order
  const omitted = Object.fromEntries(Object.values(R).map((r) => [r, []]));
  const counted = new Set();
  for (const r of idx.records.values()) {
    await breathe();
    if (r.f & F.SIDE) omitted[R.SUBAGENT].push(r.o);
    else if (r.f & F.HUGE) omitted[R.HUGE].push(r.o);
    else if (inBranch.has(r)) {
      if (r.f & F.TEAM) omitted[R.SUBAGENT].push(r.o);
      else if (r.f & F.THINK) omitted[R.THINKING].push(r.o);
      else if (r.f & F.NOTICE) omitted[R.NOTICE].push(r.o);
      else if (r.f & F.SUMMARY && !shownSummary.has(r)) omitted[R.SUMMARY].push(r.o);
    } else if (r.f & F.API_ERROR) omitted[R.NOTICE].push(r.o);
    else if (r.f & F.TEAM && r.f & (F.HUMAN | F.TEXT | F.USE)) omitted[R.SUBAGENT].push(r.o);
    else if (r.f & (F.HUMAN | F.QUEUED)) omitted[R.OTHER_BRANCH].push(r.o);
    else if (r.m && r.f & (F.TEXT | F.USE) && !counted.has(r.m)) {
      counted.add(r.m);
      omitted[R.OTHER_BRANCH].push(r.o);
    }
  }
  omitted[R.UNREADABLE] = idx.unreadable.slice();
  omitted[R.HUGE] = [...omitted[R.HUGE], ...idx.unparsedHuge].sort((a, b) => a - b);

  const byKey = new Map(units.map((u, i) => [u.key, i]));
  let viewBytes = 200 + branch.length * 48 + units.length * 220 + near.size * 48 + (coreResults.size + otherResults.size) * 100 + byMsg.size * 120 + owners.size * 100;
  for (const list of Object.values(omitted)) viewBytes += list.length * 8;
  return { units, branch, omitted, outcome, broke, compaction, byKey, viewBytes, certainEnd };
}

// What a cursor checks, so it can't go on in a history that changed under it: every
// record up to its place, as resolved, and what was left out below its cut. New
// turns only add places above it.
export async function historyDigest(view, bi, cut) {
  const h = crypto.createHash("sha1");
  for (let i = view.branch.length - 1; i >= bi; i--) {
    const r = view.branch[i];
    h.update(`${r.u}|${r.o}|${r.n}|${r.f}\n`);
    if (i % BATCH === 0) await pause();
  }
  for (const [reason, list] of Object.entries(view.omitted)) {
    h.update(`#${reason}`);
    for (const o of list) {
      if (o >= cut) break;
      h.update(`${o},`);
    }
  }
  return h.digest("hex").slice(0, 20);
}

// How many of a sorted list lie in [low, high)
const below = (list, x) => {
  let a = 0;
  let b = list.length;
  while (a < b) {
    const m = (a + b) >> 1;
    if (list[m] < x) a = m + 1;
    else b = m;
  }
  return a;
};
export const countBetween = (list, low, high) => below(list, high) - below(list, low);

// ------------------------------------------------------------------ the memo

const memo = new Map();
export const clearIndexMemo = () => memo.clear();
export const memoStats = () => ({ sessions: memo.size, bytes: [...memo.values()].reduce((n, i) => n + i.retained(), 0) });

// The least recently used make way for `keep`, whatever state they're in: ready,
// paused or refused. Applied on every way out of a call and while a scan grows. One
// evicted while another call is scanning it finishes that call and is then dropped,
// so what is over the limit lasts only as long as a call. Its next read starts again.
function evict(keep, maxMemoBytes) {
  for (const [file, idx] of memo) {
    if (memo.size <= MAX_MEMO && [...memo.values()].reduce((n, i) => n + i.retained(), 0) <= maxMemoBytes) return;
    if (idx !== keep) memo.delete(file);
  }
}

// { status: "ready", view } | { status: "scanning", scanned, total } |
// { status: "tooLarge" }. maxChunks is for tests: stop as the time limit would,
// at an exact place. Calls on one session wait for each other.
export async function openIndex(file, { scanMs = SCAN_MS, maxChunks = Infinity, maxBytes = MAX_SESSION_BYTES, maxMemoBytes = MAX_MEMO_BYTES } = {}) {
  let idx = memo.get(file);
  if (!idx) {
    idx = new SessionIndex(file, maxBytes);
    memo.set(file, idx);
  }
  const run = idx.busy.then(() => step(file, idx, { scanMs, maxChunks, maxBytes, maxMemoBytes }));
  idx.busy = run.catch(() => {});
  return run;
}

async function step(file, entry, { scanMs, maxChunks, maxBytes, maxMemoBytes }) {
  let fh;
  try {
    fh = await fs.promises.open(file, "r");
  } catch (e) {
    // nothing to remember of a file that can't be opened
    if (memo.get(file) === entry) memo.delete(file);
    throw e;
  }
  let idx = entry;
  try {
    const st = await fh.stat();
    if (idx.id && !(await sameFile(fh, st, idx.id))) {
      idx = new SessionIndex(file, maxBytes);
      idx.busy = entry.busy;
      memo.set(file, idx);
    }
    // the most recently used last
    memo.delete(file);
    memo.set(file, idx);
    idx.maxBytes = maxBytes;
    if (idx.tooLarge) {
      idx.id = await fileIdentity(fh, st, 0);
      return { status: "tooLarge" };
    }
    const done = await idx.scan(fh, st, { scanMs, maxChunks, onGrow: () => evict(idx, maxMemoBytes) });
    if (idx.tooLarge) {
      idx.id = await fileIdentity(fh, st, 0);
      return { status: "tooLarge" };
    }
    idx.id = await fileIdentity(fh, st, idx.pos);
    if (!done) return { status: "scanning", scanned: idx.pos, total: st.size };
    if (idx.viewVersion !== idx.version || !idx.view) {
      idx.view = await resolve(idx);
      idx.viewBytes = idx.view.viewBytes;
      idx.viewVersion = idx.version;
    }
    if (idx.retained() > maxBytes) {
      idx.markTooLarge();
      return { status: "tooLarge" };
    }
    return { status: "ready", view: idx.view };
  } finally {
    evict(idx, maxMemoBytes);
    await fh.close();
  }
}
